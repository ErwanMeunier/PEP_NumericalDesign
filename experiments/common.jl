# ── output locations ──────────────────────────────────────────────────────────

const EXP_ROOT = @__DIR__
for d in ("results", "figures", "tables")
    mkpath(joinpath(EXP_ROOT, d))
end
results_path(name) = joinpath(EXP_ROOT, "results", name)
figures_path(name) = joinpath(EXP_ROOT, "figures", name)
tables_path(name) = joinpath(EXP_ROOT, "tables", name)

"""Short stable hash of a config NamedTuple (artifact tagging)."""
cfg_hash(cfg) = string(hash(repr(cfg)) % UInt32; base = 16, pad = 8)

"""Save experiment data tagged with its config; returns the path."""
function save_result(name::String, cfg, data::Dict{String,Any})
    path = results_path("$(name)_$(cfg_hash(cfg)).jld2")
    jldsave(path; cfg = repr(cfg), data)
    return path
end

# ── plotting style (journal figures) ─────────────────────────────────────────

function setup_plots!()
    gr()
    default(fontfamily = "Computer Modern", linewidth = 2, framestyle = :box,
            grid = true, gridalpha = 0.25, legendfontsize = 8, guidefontsize = 11,
            tickfontsize = 9, titlefontsize = 11, dpi = 300,
            left_margin = 5Plots.mm, bottom_margin = 4Plots.mm)
end

"""Save a figure as PDF with a PNG companion."""
function save_figure(plt, name::String)
    savefig(plt, figures_path("$name.pdf"))
    savefig(plt, figures_path("$name.png"))
    return figures_path("$name.pdf")
end

